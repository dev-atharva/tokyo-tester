CREATE TABLE IF NOT EXISTS `workflow_run_intent` (
  `id` VARCHAR(255) NOT NULL PRIMARY KEY,
  `principalId` VARCHAR(255) NOT NULL,
  `userId` VARCHAR(255) NOT NULL,
  `projectId` VARCHAR(255) NOT NULL,
  `workflowId` VARCHAR(255) NOT NULL,
  `operation` ENUM('bundle', 'existing') NOT NULL,
  `state` ENUM('awaiting-human', 'submitting', 'submitted', 'cancelled', 'expired') NOT NULL DEFAULT 'awaiting-human',
  `requestHash` VARCHAR(64) NOT NULL,
  `idempotencyKey` VARCHAR(200) NOT NULL,
  `payload` LONGTEXT NOT NULL,
  `requiredSecretRefs` TEXT NOT NULL,
  `selectionSummary` TEXT NOT NULL,
  `workflowRunId` VARCHAR(255) NULL,
  `claimId` VARCHAR(255) NULL,
  `createdAt` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `expiresAt` TIMESTAMP NOT NULL,
  `updatedAt` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT `workflow_run_intent_user_fk` FOREIGN KEY (`userId`) REFERENCES `user` (`id`) ON DELETE CASCADE,
  CONSTRAINT `workflow_run_intent_project_fk` FOREIGN KEY (`projectId`) REFERENCES `project` (`id`) ON DELETE CASCADE,
  UNIQUE KEY `workflow_run_intent_request_idx` (`principalId`, `projectId`, `operation`, `idempotencyKey`),
  KEY `workflow_run_intent_human_idx` (`userId`, `projectId`, `id`),
  KEY `workflow_run_intent_expiry_idx` (`state`, `expiresAt`)
);
